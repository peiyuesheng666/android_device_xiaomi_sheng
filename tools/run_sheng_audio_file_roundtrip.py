"""Check generated lossless audio through MediaExtractor and an installed codec."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import uuid


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build', type=Path, required=True)
    parser.add_argument('--fixture', type=Path, required=True,
                        help='One second of the PCM waveform generated by ShengAudioCodec2RoundTrip')
    parser.add_argument('--codec', required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--native-alac-config', action='store_true',
                        help='Diagnostic override; success does not qualify the unmodified media path')
    parser.add_argument('--reference-info', type=Path,
                        help='Independent decoder receipt with fixture and 16-bit PCM hashes and ffprobe metadata')
    parser.add_argument('--default-decoder', action='store_true',
                        help='Use the platform default and require that it matches --codec')
    parser.add_argument('--seek-us', type=int,
                        help='Seek through MediaExtractor; reference-info must describe the expected PCM suffix')
    stream_modes = parser.add_mutually_exclusive_group()
    stream_modes.add_argument('--ape-byte-stream', action='store_true',
                        help='Diagnostic only: feed APE audio without MediaExtractor')
    stream_modes.add_argument('--ape-frame-stream', action='store_true',
                        help='Diagnostic only: feed framed APE audio without MediaExtractor')
    args = parser.parse_args()
    assert re.fullmatch(r'c2\.qti\.(alac|ape)\.(sw|hw)\.decoder', args.codec)
    assert not args.native_alac_config or '.alac.' in args.codec
    assert not (args.native_alac_config and args.reference_info)
    ape_direct = args.ape_byte_stream or args.ape_frame_stream
    assert not ape_direct or (args.reference_info and '.ape.' in args.codec)
    assert not (args.default_decoder or args.seek_us is not None) or (args.reference_info and not ape_direct)
    assert args.seek_us is None or 0 <= args.seek_us < 2**63
    tools = Path(__file__).resolve().parent
    workspace = tools.parents[3]
    adb = workspace / 'tools/platform-tools/adb.exe'
    build = json.loads((args.build / 'build.json').read_text())
    source = tools / ('ShengLosslessAudioFileProbe.java' if args.reference_info else 'ShengAudioCodec2RoundTrip.java')
    jar = args.build / ('sheng-lossless-audio-file.jar' if args.reference_info else 'sheng-audio-codec2-roundtrip.jar')
    assert build['passed'] and not build['ninja_graph_loaded']
    assert sha(source) == build['source_sha256'] and sha(jar) == build['jar_sha256']
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    files = {'probe.jar': jar, 'generated.audio': args.fixture.resolve(strict=True)}
    for name, path in files.items():
        shutil.copyfile(path, output / name)
    remote = '/data/local/tmp/sheng-audio-file-' + uuid.uuid4().hex[:12]
    receipt = dict(passed=False, started_utc=datetime.now(timezone.utc).isoformat(),
                   source_sha256=sha(source), jar_sha256=sha(jar), fixture_sha256=sha(args.fixture),
                   codec=args.codec, native_config_override=args.native_alac_config,
                   ape_byte_stream_diagnostic=args.ape_byte_stream,
                   ape_frame_stream_diagnostic=args.ape_frame_stream,
                   default_decoder_selection=args.default_decoder, seek_us=args.seek_us,
                   microphone_used=False, playback_used=False, commands=[])
    reference = None
    if args.reference_info:
        reference = json.loads(args.reference_info.read_text())
        assert reference['fixture_sha256'] == sha(args.fixture)
        assert re.fullmatch(r'[0-9a-f]{64}', reference['reference_pcm_sha256'])
        assert 0 < reference['reference_pcm_bytes'] <= 64 * 1024**2
        stream = reference['ffprobe']['streams'][0]
        assert 1 <= int(stream['channels']) <= 8 and 8000 <= int(stream['sample_rate']) <= 384000
        receipt['reference_info_sha256'] = sha(args.reference_info)

    def call(label, *arguments, check=True):
        result = subprocess.run([str(adb), '-s', 'ca10ede3', *arguments], capture_output=True, timeout=45)
        (output / (label + '.stdout')).write_bytes(result.stdout)
        (output / (label + '.stderr')).write_bytes(result.stderr)
        receipt['commands'].append(dict(label=label, arguments=arguments, returncode=result.returncode))
        if check:
            result.check_returncode()
        return result

    def shell(label, command):
        return call(label, 'shell', command).stdout.decode(errors='replace').strip()

    def state(label):
        value = shell(label, 'getprop sys.boot_completed; getenforce; cat /proc/sys/kernel/random/boot_id; '
                      'ps -A')
        lines = value.splitlines()
        names = {'media.audio.qc.codec', 'media.hwcodec', 'mediaserver',
                 'dolbycodec2', 'vendor.dolby.media.c2@1.0-service'}
        services = {row[-1]: int(row[1]) for row in (line.split() for line in lines[3:])
                    if row and row[-1] in names}
        assert lines[:2] == ['1', 'Enforcing'] and set(services) == names
        assert re.fullmatch(r'[0-9a-f-]{36}', lines[2])
        return dict(boot_id=lines[2], selinux=lines[1], services=services)

    created = False
    try:
        receipt['before'] = state('before')
        shell('prepare', 'test ! -e ' + remote + ' && mkdir -m 0700 ' + remote)
        created = True
        for name, path in files.items():
            windows = subprocess.check_output(['wslpath', '-w', str(output / name)], text=True).strip()
            # An explicit destination avoids adb truncating a basename derived
            # from a Windows source path containing multibyte characters.
            call('push-' + name, 'push', windows, remote + '/' + name)
            assert shell('hash-' + name, 'sha256sum ' + remote + '/' + name).split()[0] == sha(path)
        shell('inputs-readonly', 'chmod 0444 ' + remote + '/probe.jar ' + remote + '/generated.audio')
        option = '--file-alac-native-config' if args.native_alac_config else '--file'
        entry = 'ShengAudioCodec2RoundTrip ' + option + ' ' + args.codec + ' ' + remote + '/generated.audio'
        if reference:
            entry = 'ShengLosslessAudioFileProbe ' + args.codec + ' ' + remote + '/generated.audio ' + \
                str(int(stream['sample_rate'])) + ' ' + str(int(stream['channels'])) + ' ' + \
                str(reference['reference_pcm_bytes']) + ' ' + reference['reference_pcm_sha256']
            if args.ape_byte_stream:
                entry += ' --ape-byte-stream'
            if args.ape_frame_stream:
                entry += ' --ape-frame-stream'
            if args.default_decoder:
                entry += ' --default-decoder'
            if args.seek_us is not None:
                entry += ' --seek-us=' + str(args.seek_us)
        result = call('decode', 'shell', 'CLASSPATH=' + remote + '/probe.jar timeout 30 app_process / '
                      + entry,
                      check=False)
        decoded = (result.stdout + result.stderr).decode(errors='replace')
        print(decoded, flush=True)
        result.check_returncode()
        if reference:
            assert 'AUDIO_FILE_REFERENCE passed=true codec=' + args.codec + ' bytes=' + \
                str(reference['reference_pcm_bytes']) + ' sha256=' + reference['reference_pcm_sha256'] in decoded
            if args.default_decoder:
                assert 'AUDIO_FILE_CODEC actual=' + args.codec + ' automatic=true' in decoded
            receipt.update(passed=True, exact_pcm_samples=reference['reference_pcm_bytes'] // 2,
                           reference_pcm_sha256=reference['reference_pcm_sha256'],
                           extractor_used=not ape_direct)
        else:
            assert 'AUDIO_FILE_DECODE passed=true codec=' + args.codec in decoded
            assert 'AUDIO_CONTENT lossless=true exact_samples=96000' in decoded
            receipt.update(passed=True, exact_pcm_samples=96000, extractor_used=True)
    except BaseException as error:
        receipt.update(passed=False, error=repr(error))
    finally:
        try:
            receipt['after'] = state('after')
            assert receipt['after'] == receipt.get('before'), 'Boot or codec service identity changed'
            call('logcat', 'logcat', '-b', 'all', '-d', '-v', 'threadtime')
            if created:
                cleanup = call('cleanup', 'shell', 'rm -f ' + remote + '/probe.jar ' + remote + '/generated.audio'
                               ' && rmdir ' + remote, check=False)
                receipt['temporary_files_removed'] = cleanup.returncode == 0
                assert receipt['temporary_files_removed']
        except BaseException as error:
            receipt.update(passed=False, cleanup_or_state_error=repr(error))
        receipt['finished_utc'] = datetime.now(timezone.utc).isoformat()
        (output / 'receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    if not receipt['passed']:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
